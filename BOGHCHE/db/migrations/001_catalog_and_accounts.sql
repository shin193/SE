CREATE TABLE categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 1 AND 120),
  position integer NOT NULL DEFAULT 0
);

CREATE TABLE products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL REFERENCES categories(id),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 160),
  price integer NOT NULL CHECK (price >= 0),
  description text NOT NULL,
  material text NOT NULL,
  dimensions text NOT NULL,
  usage text NOT NULL,
  care text NOT NULL,
  featured boolean NOT NULL DEFAULT false,
  is_new boolean NOT NULL DEFAULT false
);
CREATE INDEX products_category ON products (category_id, id);

CREATE TABLE product_images (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  src text NOT NULL CHECK (src LIKE 'assets/%' OR src LIKE 'https://%'),
  alt text NOT NULL,
  atlas_cell integer CHECK (atlas_cell BETWEEN 0 AND 8),
  position integer NOT NULL DEFAULT 0,
  UNIQUE (product_id, id)
);

CREATE TABLE product_variants (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
  hex text NOT NULL CHECK (hex ~ '^#[0-9a-fA-F]{6}$'),
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  image_id integer,
  position integer NOT NULL DEFAULT 0,
  UNIQUE (product_id, name),
  FOREIGN KEY (product_id, image_id) REFERENCES product_images(product_id, id)
    ON DELETE SET NULL (image_id)
);

CREATE TABLE accounts (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (char_length(name) BETWEEN 2 AND 60),
  email text NOT NULL UNIQUE CHECK (char_length(email) BETWEEN 3 AND 254),
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sessions (
  token_hash text PRIMARY KEY,
  account_id integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL
);
CREATE INDEX sessions_expiry ON sessions (expires_at);

CREATE TABLE reviews (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  account_id integer NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body text NOT NULL CHECK (char_length(body) BETWEEN 10 AND 1000),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (product_id, account_id)
);
CREATE INDEX reviews_product_date ON reviews (product_id, updated_at DESC, id DESC);
